#!/usr/bin/env node
// Converts design/icons/*.svg (24 px, 1.75 stroke, currentColor) into Android vector drawables
// app/src/main/res/drawable/ic_<name>.xml. Tint is applied at use site (Compose Icon tint).
// Also writes the launcher foreground from design/brand/logo-mark.svg.
// Usage: node tools/icons-to-vectors.mjs [--check]
import { readFileSync, writeFileSync, readdirSync, mkdirSync, existsSync } from 'node:fs';
import { join, dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const iconDir = join(root, 'design/icons');
const outDir = join(root, 'app/src/main/res/drawable');
const check = process.argv.includes('--check');

const attr = (el, name) => (el.match(new RegExp(`\\s${name}="([^"]*)"`)) ?? [])[1];

export function svgToVector(svg) {
  const width = Number(attr(svg.match(/<svg[^>]*>/)[0], 'width') ?? 24);
  const height = Number(attr(svg.match(/<svg[^>]*>/)[0], 'height') ?? 24);
  const lines = [
    '<?xml version="1.0" encoding="utf-8"?>',
    '<!-- GENERATED by tools/icons-to-vectors.mjs from design/icons. Do not edit by hand. -->',
    `<vector xmlns:android="http://schemas.android.com/apk/res/android"`,
    `    android:width="${width}dp"`,
    `    android:height="${height}dp"`,
    `    android:viewportWidth="${width}"`,
    `    android:viewportHeight="${height}">`,
  ];
  const group = svg.match(/<g[^>]*transform="translate\(([-\d.]+)[ ,]+([-\d.]+)\)"[^>]*>/);
  const indent = group ? '        ' : '    ';
  if (group) lines.push(`    <group android:translateX="${group[1]}" android:translateY="${group[2]}">`);
  for (const [el] of svg.matchAll(/<path\b[^>]*\/>/g)) {
    const d = attr(el, 'd');
    const sw = attr(el, 'stroke-width') ?? '1.75';
    const cap = attr(el, 'stroke-linecap') ?? 'round';
    const join = attr(el, 'stroke-linejoin') ?? 'round';
    lines.push(`${indent}<path`);
    lines.push(`${indent}    android:fillColor="#00000000"`);
    lines.push(`${indent}    android:pathData="${d}"`);
    lines.push(`${indent}    android:strokeColor="#FF000000"`);
    lines.push(`${indent}    android:strokeLineCap="${cap}"`);
    lines.push(`${indent}    android:strokeLineJoin="${join}"`);
    lines.push(`${indent}    android:strokeWidth="${sw}" />`);
  }
  if (group) lines.push('    </group>');
  lines.push('</vector>');
  return lines.join('\n') + '\n';
}

const outputs = [];
for (const file of readdirSync(iconDir).filter((f) => f.endsWith('.svg')).sort()) {
  const name = 'ic_' + file.replace(/\.svg$/, '').replace(/-/g, '_');
  outputs.push([join(outDir, name + '.xml'), svgToVector(readFileSync(join(iconDir, file), 'utf8'))]);
}

// Vector drawables have no stroke-dasharray, so the dashed hop route is expanded into segments.
function dashedPolyline(points, dash, gap) {
  const segs = [];
  let on = true;
  let left = dash;
  for (let i = 0; i < points.length - 1; i++) {
    let [x, y] = points[i];
    const [x2, y2] = points[i + 1];
    let len = Math.hypot(x2 - x, y2 - y);
    const ux = (x2 - x) / len;
    const uy = (y2 - y) / len;
    while (len > 1e-6) {
      const step = Math.min(left, len);
      const nx = x + ux * step;
      const ny = y + uy * step;
      if (on) segs.push(`M${x.toFixed(3)},${y.toFixed(3)} L${nx.toFixed(3)},${ny.toFixed(3)}`);
      x = nx;
      y = ny;
      len -= step;
      left -= step;
      if (left <= 1e-6) {
        on = !on;
        left = on ? dash : gap;
      }
    }
  }
  return segs.join(' ');
}
const route = dashedPolyline([[8, 23], [15, 12], [24, 18]], 2, 3.5);

// Adaptive launcher icon foreground: the logo route on the ink background (108dp canvas, 72dp safe zone).
const foreground = `<?xml version="1.0" encoding="utf-8"?>
<!-- GENERATED by tools/icons-to-vectors.mjs from design/brand/logo-mark.svg. Do not edit by hand. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="108dp"
    android:height="108dp"
    android:viewportWidth="108"
    android:viewportHeight="108">
    <group android:scaleX="2.25" android:scaleY="2.25" android:translateX="18" android:translateY="18">
        <path
            android:fillColor="#00000000"
            android:pathData="${route}"
            android:strokeColor="#FFFFFFFF"
            android:strokeLineCap="round"
            android:strokeLineJoin="round"
            android:strokeWidth="2" />
        <path android:fillColor="#FFFFFFFF" android:pathData="M8,23m-2.5,0a2.5,2.5 0,1 1,5 0a2.5,2.5 0,1 1,-5 0" />
        <path android:fillColor="#FFFFFFFF" android:pathData="M15,12m-2.5,0a2.5,2.5 0,1 1,5 0a2.5,2.5 0,1 1,-5 0" />
        <path android:fillColor="#FFE6AE19" android:pathData="M24,18m-4,0a4,4 0,1 1,8 0a4,4 0,1 1,-8 0" />
    </group>
</vector>
`;
outputs.push([join(outDir, 'ic_launcher_foreground.xml'), foreground]);

let stale = false;
mkdirSync(outDir, { recursive: true });
for (const [path, content] of outputs) {
  if (check) {
    const current = existsSync(path) ? readFileSync(path, 'utf8').replace(/\r\n/g, '\n') : '';
    if (current !== content) {
      console.error(`stale: ${path} (run node tools/icons-to-vectors.mjs)`);
      stale = true;
    }
  } else {
    writeFileSync(path, content);
  }
}
if (!check) console.log(`wrote ${outputs.length} vector drawables to ${outDir}`);
if (stale) process.exit(1);
