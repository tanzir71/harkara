#!/usr/bin/env node
// Generates the Android token object and the site CSS variables from design/tokens/tokens.json.
// Usage: node tools/build-tokens.mjs [--check]
import { readFileSync, writeFileSync, mkdirSync, existsSync } from 'node:fs';
import { join, dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const tokens = JSON.parse(readFileSync(join(root, 'design/tokens/tokens.json'), 'utf8'));
const check = process.argv.includes('--check');

const camel = (name) =>
  name
    .split(/[\/\- ]+/)
    .map((part, i) => (i === 0 ? part.toLowerCase() : part[0].toUpperCase() + part.slice(1).toLowerCase()))
    .join('');
const cssVar = (name) => '--' + name.replace(/\//g, '-').toLowerCase();
const argb = (hex) => '0xFF' + hex.replace('#', '').toUpperCase();

const colorNames = Object.keys(tokens.color);
const dims = tokens.dimension;
const text = tokens.text;

// ---------- Kotlin ----------
const kt = [];
kt.push('// GENERATED by tools/build-tokens.mjs from design/tokens/tokens.json. Do not edit by hand.');
kt.push('package io.github.tanzir71.harkara.ui.theme');
kt.push('');
kt.push('import androidx.compose.runtime.Immutable');
kt.push('import androidx.compose.ui.graphics.Color');
kt.push('import androidx.compose.ui.unit.dp');
kt.push('import androidx.compose.ui.unit.sp');
kt.push('');
kt.push('/** Colour tokens for one theme mode (Day or Night). */');
kt.push('@Immutable');
kt.push('data class HarkaraColors(');
for (const n of colorNames) kt.push(`    /** ${n} */\n    val ${camel(n)}: Color,`);
kt.push(')');
kt.push('');
kt.push('/** One text style token. Sizes are sp, letter spacing is sp (px on the web). */');
kt.push('@Immutable');
kt.push('data class TextToken(');
kt.push('    val family: String,');
kt.push('    val weight: Int,');
kt.push('    val size: Float,');
kt.push('    val lineHeight: Float,');
kt.push('    val letterSpacing: Float,');
kt.push('    val uppercase: Boolean = false,');
kt.push(') {');
kt.push('    val sizeSp get() = size.sp');
kt.push('    val lineHeightSp get() = lineHeight.sp');
kt.push('    val letterSpacingSp get() = letterSpacing.sp');
kt.push('}');
kt.push('');
kt.push('/** Design tokens exported from Figma (Local-Dhaka file). */');
kt.push('object Tokens {');
for (const mode of ['Day', 'Night']) {
  kt.push(`    val ${mode} = HarkaraColors(`);
  for (const n of colorNames) kt.push(`        ${camel(n)} = Color(${argb(tokens.color[n][mode])}),`);
  kt.push('    )');
  kt.push('');
}
kt.push('    object Space {');
for (const [k, v] of Object.entries(dims).filter(([k]) => k.startsWith('space/'))) {
  kt.push(`        val s${k.split('/')[1]} = ${v}.dp`);
}
kt.push('    }');
kt.push('');
kt.push('    object Radius {');
for (const [k, v] of Object.entries(dims).filter(([k]) => k.startsWith('radius/'))) {
  kt.push(`        val ${k.split('/')[1]} = ${v}.dp`);
}
kt.push('    }');
kt.push('');
kt.push('    object Text {');
for (const [k, v] of Object.entries(text)) {
  const id = camel(k.replace(/^Web\//, 'web ').replace(/^Bangla\//, 'bangla ').replace(/^Mono\//, 'mono '));
  kt.push(
    `        val ${id} = TextToken("${v.family}", ${v.weight}, ${v.size}f, ${v.lineHeight}f, ${v.letterSpacing}f${v.textTransform === 'uppercase' ? ', uppercase = true' : ''})`,
  );
}
kt.push('    }');
kt.push('');
kt.push('    object Elevation {');
for (const [k, v] of Object.entries(tokens.elevation)) {
  const m = v.match(/^(-?\d+)(?:px)?\s+(-?\d+)(?:px)?\s+(\d+)(?:px)?\s+rgba\(([^)]+)\)$/);
  const alpha = m ? Number(m[4].split(',')[3]) : 0.1;
  kt.push(`        /** ${v} */`);
  kt.push(`        val ${k} = ${m ? Number(m[3]) / 2 : 1}.dp`);
  kt.push(`        const val ${k}Alpha = ${alpha}f`);
}
kt.push('    }');
kt.push('}');
kt.push('');
const ktOut = kt.join('\n');

// ---------- CSS ----------
const css = [];
css.push('/* GENERATED by tools/build-tokens.mjs from design/tokens/tokens.json. Do not edit by hand. */');
const block = (mode) => colorNames.map((n) => `  ${cssVar(n)}: ${tokens.color[n][mode]};`);
css.push(':root, [data-theme="day"] {');
css.push(...block('Day'));
for (const [k, v] of Object.entries(dims)) css.push(`  ${cssVar(k)}: ${v}px;`);
for (const [k, v] of Object.entries(tokens.elevation)) css.push(`  --shadow-${k}: ${v};`);
for (const [k, v] of Object.entries(text)) {
  const id = cssVar('text/' + k.replace(/ /g, '-'));
  css.push(`  ${id}-size: ${v.size}px;`);
  css.push(`  ${id}-line: ${v.lineHeight}px;`);
  css.push(`  ${id}-tracking: ${v.letterSpacing}px;`);
  css.push(`  ${id}-weight: ${v.weight};`);
}
css.push('  color-scheme: light;');
css.push('}');
css.push('@media (prefers-color-scheme: dark) {');
css.push('  :root:not([data-theme="day"]) {');
css.push(...block('Night').map((l) => '  ' + l));
css.push('    color-scheme: dark;');
css.push('  }');
css.push('}');
css.push('[data-theme="night"] {');
css.push(...block('Night'));
css.push('  color-scheme: dark;');
css.push('}');
css.push('');
const cssOut = css.join('\n');

const targets = [
  [join(root, 'app/src/main/kotlin/io/github/tanzir71/harkara/ui/theme/Tokens.kt'), ktOut],
  [join(root, 'site/assets/tokens.css'), cssOut],
];

let stale = false;
for (const [path, content] of targets) {
  if (check) {
    const current = existsSync(path) ? readFileSync(path, 'utf8').replace(/\r\n/g, '\n') : '';
    if (current !== content) {
      console.error(`stale: ${path} (run node tools/build-tokens.mjs)`);
      stale = true;
    }
  } else {
    mkdirSync(dirname(path), { recursive: true });
    writeFileSync(path, content);
    console.log(`wrote ${path}`);
  }
}
if (stale) process.exit(1);
